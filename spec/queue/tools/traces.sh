#!/bin/sh
# Regenerates the traces the delivery loop is replayed against
# (crates/minicloud/src/queue_host/mbt.rs), into
# crates/minicloud/tests/queue_traces, which is emptied first:
#
# - min_NNN: 200 random runs of `mbtStep` on MBT_MIN, 100 steps each;
# - witness_<invariant>: one run of `mbtStep` on MBT_ONE (or MBT_MIN) that
#   breaks a reachability invariant, so that the behaviour it names is in
#   the corpus for certain. The invariant is only checked between ticks,
#   so a witness ends where the replay can compare.
#
# `quint run --mbt`, a fixed seed and one thread: the same model gives the
# same files. tools/itf-pack.py drops the time of making from each trace
# and gzips it.
cd "$(dirname "$0")/.." || exit 2
dest=../../crates/minicloud/tests/queue_traces
mkdir -p out
rm -rf "$dest"
mkdir -p "$dest"
module() { # name config
  cat > "out/$1.qnt" <<EOF
// Generated by tools/traces.sh: queue.qnt with $2.
module $1 {
  import configs.* from "../configs"
  import queue(C = $2).* from "../queue"
}
EOF
  rm -rf "out/$1"
  mkdir -p "out/$1"
}
run() { # name invariant traces samples steps seed
  npx quint run --main="$1" --step=mbtStep --mbt --invariant="$2" \
    --n-traces="$3" --max-samples="$4" --max-steps="$5" --seed="$6" --n-threads=1 \
    --verbosity=1 --out-itf="out/$1/{seq}.itf.json" "out/$1.qnt"
}

module traces_min MBT_MIN
run traces_min NoOverflow 200 200 100 20261025 || exit 1
for f in out/traces_min/*.itf.json; do
  n=$(basename "$f" .itf.json)
  python3 -I tools/itf-pack.py "$f" "$dest/min_$(printf '%03d' "$n").itf.json.gz" || exit 1
done
rm -rf out/traces_min

witness() { # invariant config steps
  module "witness_$1" "$2"
  # a violation is what is wanted: quint exits 1 then
  run "witness_$1" "tpc != \"idle\" or $1" 1 100000 "$3" 1 > "out/witness_$1.txt"
  if ! grep -q "violation" "out/witness_$1.txt"; then
    echo "no witness for $1"; exit 1
  fi
  python3 -I tools/itf-pack.py "out/witness_$1/0.itf.json" "$dest/witness_$1.itf.json.gz" || exit 1
  rm -rf "out/witness_$1"
}
witness NeverHeld MBT_ONE 10
witness NeverHeldPastLease MBT_ONE 12
witness NeverDone MBT_ONE 16
witness NeverSecondAttempt MBT_ONE 20
witness NeverFail MBT_ONE 28
witness NeverOutlived MBT_ONE 30
witness NeverAllQueuesBusy MBT_MIN 18

echo "$(ls "$dest" | wc -l | tr -d ' ') traces, $(cat "$dest"/* | wc -c | tr -d ' ') bytes"
